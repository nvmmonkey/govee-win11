  const LANGS = ["zh", "en"];
  let lang = "zh";

  function t(key, params) {
    const table = TABLES[lang] || TABLES.zh;
    if (params && params.n === 1 && (key + ".one") in table) key += ".one";
    let s = table[key];
    if (s === undefined) s = TABLES.zh[key];
    if (s === undefined) return key;
    if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
    return s;
  }
  const has = (key) => key in TABLES.zh;

  /** "zh" | "en" from a browser language tag (fallback when the backend can't say). */
  function fromTag(tag) {
    return /^zh\b/i.test(String(tag || "")) ? "zh" : "en";
  }
  function guess() {
    const nav = window.navigator || {};
    return fromTag((nav.languages && nav.languages[0]) || nav.language);
  }

  function setLang(l) {
    lang = LANGS.includes(l) ? l : "zh";
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
    return lang;
  }

  /** Fill data-i18n / data-i18n-title / data-i18n-placeholder under root. */
  function apply(root) {
    root = root || document;
    root.querySelectorAll("[data-i18n]").forEach((e) => { e.textContent = t(e.dataset.i18n); });
    root.querySelectorAll("[data-i18n-title]").forEach((e) => { e.title = t(e.dataset.i18nTitle); });
    root.querySelectorAll("[data-i18n-placeholder]").forEach((e) => { e.placeholder = t(e.dataset.i18nPlaceholder); });
  }

  const clean = (s) => String(s || "").replace(/ /g, " ").trim();
  /** Scene category / name in the current language (catalogue names are English). */
  function sceneCategory(cat) {
    const c = clean(cat);
    return lang === "zh" ? SCENE_CATS_ZH[c] || c : c;
  }
  function sceneNames(cat, name) {
    const en = clean(name);
    const zh = SCENE_NAMES_ZH_BY_CAT[clean(cat) + "|" + en] || SCENE_NAMES_ZH[en] || en;
    return { zh, en, title: lang === "zh" ? zh : en };
  }

  window.GoveeI18n = {
    t, has, setLang, apply, guess, fromTag, sceneCategory, sceneNames, clean,
    lang: () => lang, languages: LANGS,
  };
